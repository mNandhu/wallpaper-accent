"""fzf: --color opts. Applies to new shells (env is per-process)."""
from __future__ import annotations

from .. import config
from ..util import atomic_write


def emit(pal: dict) -> None:
    s, a = pal["surface"], pal["accent"]
    color = ",".join(
        [
            f"bg+:{a['secondary_container']}",
            f"bg:{s['bg']}",
            f"fg:{s['fg_variant']}",
            f"fg+:{s['fg']}",
            f"hl:{a['secondary']}",
            f"hl+:{a['secondary']}",
            f"prompt:{a['primary']}",
            f"pointer:{a['primary']}",
            f"marker:{a['tertiary']}",
            f"spinner:{a['tertiary']}",
            f"info:{a['secondary']}",
            f"header:{a['tertiary']}",
            f"border:{s['outline']}",
        ]
    )
    body = f"""\
# GENERATED by wallpaper-accent — do not edit. Sourced from .zshrc.local.
export FZF_DEFAULT_OPTS="${{FZF_DEFAULT_OPTS:-}} --color={color}"
"""
    atomic_write(config.FZF_ENV, body)
